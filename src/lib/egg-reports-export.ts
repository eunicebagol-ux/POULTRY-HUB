import * as XLSX from "xlsx";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import type { EggProductionPeriodReport } from "@/types/egg-reports";

export interface ExportMetadata {
  generatedAt: string; // ISO or formatted date
  generatedBy: string; // Admin full name
  farmName?: string;
}

/**
 * Generates an Excel (.xlsx) file buffer from the egg production report.
 */
export function generateEggReportExcel(
  report: EggProductionPeriodReport,
  metadata: ExportMetadata
): Buffer {
  const wb = XLSX.utils.book_new();

  // 1. Build Header & Summary rows
  const aoaData: (string | number)[][] = [
    ["POULTRY HUB — Egg Production Report"],
    ["Farm Management System", "", "", "", "", "", "", ""],
    [],
    ["REPORT METADATA"],
    ["Reporting Period:", report.period.toUpperCase()],
    ["Date Range:", report.formattedDateRange],
    ["Generated At:", metadata.generatedAt],
    ["Generated By:", metadata.generatedBy],
    [],
    ["PRODUCTION KPI SUMMARY"],
    ["Total Eggs Collected", report.summary.totalEggs],
    ["Good Eggs (Clean & Whole)", report.summary.goodEggs, `${report.summary.goodEggsRate}%`],
    ["Cracked Eggs", report.summary.crackedEggs, `${report.summary.crackedEggsRate}%`],
    ["Damaged Eggs", report.summary.damagedEggs, `${report.summary.damagedEggsRate}%`],
    [report.summary.averageLabel, report.summary.periodAverage],
    ["Total Collections Logged", report.summary.recordCount],
    [],
    ["DETAILED PRODUCTION RECORDS"],
    [
      "Date",
      "Shift",
      "Flock Identifier",
      "Breed",
      "Total Eggs",
      "Good Eggs",
      "Cracked Eggs",
      "Damaged Eggs",
      "Good Egg Rate",
      "Notes",
    ],
  ];

  // 2. Add detailed record rows
  if (report.records.length === 0) {
    aoaData.push(["No production records recorded for this period."]);
  } else {
    for (const r of report.records) {
      const goodRate = r.total_eggs > 0 ? ((r.good_eggs / r.total_eggs) * 100).toFixed(1) + "%" : "0.0%";
      aoaData.push([
        r.production_date,
        r.collection_shift || "Unspecified",
        r.flock_identifier,
        r.flock_breed || "—",
        r.total_eggs,
        r.good_eggs,
        r.cracked_eggs,
        r.damaged_eggs,
        goodRate,
        r.notes || "",
      ]);
    }

    // Totals Row
    aoaData.push([
      "TOTAL / SUMMARY",
      "",
      `${report.records.length} records`,
      "",
      report.summary.totalEggs,
      report.summary.goodEggs,
      report.summary.crackedEggs,
      report.summary.damagedEggs,
      `${report.summary.goodEggsRate}%`,
      "",
    ]);
  }

  const ws = XLSX.utils.aoa_to_sheet(aoaData);

  // Set column widths
  ws["!cols"] = [
    { wch: 15 }, // Date
    { wch: 14 }, // Shift
    { wch: 20 }, // Flock
    { wch: 18 }, // Breed
    { wch: 14 }, // Total Eggs
    { wch: 14 }, // Good Eggs
    { wch: 14 }, // Cracked
    { wch: 14 }, // Damaged
    { wch: 16 }, // Good Rate
    { wch: 30 }, // Notes
  ];

  XLSX.utils.book_append_sheet(wb, ws, "Egg Production Report");

  const buffer = XLSX.write(wb, { type: "buffer", bookType: "xlsx" });
  return Buffer.isBuffer(buffer) ? buffer : Buffer.from(buffer);
}

/**
 * Generates an RFC 4180-compliant CSV buffer with UTF-8 BOM.
 */
export function generateEggReportCSV(
  report: EggProductionPeriodReport,
  metadata: ExportMetadata
): Buffer {
  const lines: string[] = [];

  // Metadata headers
  lines.push(`# POULTRY HUB — Egg Production Report`);
  lines.push(`# Reporting Period: ${report.period.toUpperCase()}`);
  lines.push(`# Date Range: ${report.formattedDateRange}`);
  lines.push(`# Generated At: ${metadata.generatedAt}`);
  lines.push(`# Generated By: ${metadata.generatedBy}`);
  lines.push(`# Total Eggs: ${report.summary.totalEggs}`);
  lines.push(`# Good Eggs: ${report.summary.goodEggs} (${report.summary.goodEggsRate}%)`);
  lines.push(`# Cracked Eggs: ${report.summary.crackedEggs} (${report.summary.crackedEggsRate}%)`);
  lines.push(`# Damaged Eggs: ${report.summary.damagedEggs} (${report.summary.damagedEggsRate}%)`);
  lines.push(`# ${report.summary.averageLabel}: ${report.summary.periodAverage}`);
  lines.push(``);

  // Column Headers
  lines.push(
    `"Production Date","Shift","Flock Identifier","Breed","Total Eggs","Good Eggs","Cracked Eggs","Damaged Eggs","Good Egg Rate","Notes"`
  );

  // Records
  if (report.records.length === 0) {
    lines.push(`"No production records for this period",,,,,,,,,`);
  } else {
    for (const r of report.records) {
      const goodRate = r.total_eggs > 0 ? ((r.good_eggs / r.total_eggs) * 100).toFixed(1) + "%" : "0.0%";
      const notesClean = (r.notes || "").replace(/"/g, '""');
      lines.push(
        `"${r.production_date}","${r.collection_shift || "Unspecified"}","${r.flock_identifier}","${r.flock_breed || ""}","${r.total_eggs}","${r.good_eggs}","${r.cracked_eggs}","${r.damaged_eggs}","${goodRate}","${notesClean}"`
      );
    }

    // Totals
    lines.push(
      `"TOTAL / SUMMARY","","${report.records.length} records","","${report.summary.totalEggs}","${report.summary.goodEggs}","${report.summary.crackedEggs}","${report.summary.damagedEggs}","${report.summary.goodEggsRate}%",""`
    );
  }

  // Prepend UTF-8 BOM (\uFEFF)
  const csvContent = "\uFEFF" + lines.join("\r\n");
  return Buffer.from(csvContent, "utf-8");
}

/**
 * Generates a clean, printable PDF report using jsPDF & autotable.
 */
export function generateEggReportPDF(
  report: EggProductionPeriodReport,
  metadata: ExportMetadata
): Buffer {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 14;

  // 1. Top Decorative Brand Bar
  doc.setFillColor(5, 150, 105); // emerald-600
  doc.rect(0, 0, pageWidth, 5, "F");

  // 2. Header
  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.setTextColor(15, 23, 42); // slate-900
  doc.text("POULTRY HUB", margin, 18);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139); // slate-500
  doc.text("Poultry Egg Production Management System", margin, 23);

  // Report Title (Right Aligned or Subheader)
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.setTextColor(5, 150, 105);
  doc.text(`${report.period.toUpperCase()} PRODUCTION REPORT`, margin, 32);

  // Metadata Box
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  doc.text(`Period: ${report.formattedDateRange}`, margin, 38);
  doc.text(`Generated: ${metadata.generatedAt} (PHT)`, margin, 43);
  doc.text(`Authorized Officer: ${metadata.generatedBy}`, margin, 48);

  // 3. KPI Summary Box (Grid)
  const kpiTop = 53;
  const kpiHeight = 22;
  const colWidth = (pageWidth - margin * 2) / 4;

  // Box background
  doc.setFillColor(248, 250, 252); // slate-50
  doc.setDrawColor(226, 232, 240); // slate-200
  doc.roundedRect(margin, kpiTop, pageWidth - margin * 2, kpiHeight, 2, 2, "FD");

  // KPI 1: Total Eggs
  doc.setFont("helvetica", "bold");
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text("TOTAL EGGS", margin + 5, kpiTop + 7);
  doc.setFontSize(13);
  doc.setTextColor(15, 23, 42);
  doc.text(report.summary.totalEggs.toLocaleString(), margin + 5, kpiTop + 16);

  // KPI 2: Good Eggs
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text("GOOD EGGS", margin + colWidth + 5, kpiTop + 7);
  doc.setFontSize(13);
  doc.setTextColor(5, 150, 105); // emerald
  doc.text(`${report.summary.goodEggs.toLocaleString()} (${report.summary.goodEggsRate}%)`, margin + colWidth + 5, kpiTop + 16);

  // KPI 3: Cracked & Damaged
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text("CRACKED / DAMAGED", margin + colWidth * 2 + 5, kpiTop + 7);
  doc.setFontSize(13);
  doc.setTextColor(225, 29, 72); // rose-600
  doc.text(
    `${report.summary.crackedEggs.toLocaleString()} / ${report.summary.damagedEggs.toLocaleString()}`,
    margin + colWidth * 2 + 5,
    kpiTop + 16
  );

  // KPI 4: Period Average
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text(report.summary.averageLabel.toUpperCase(), margin + colWidth * 3 + 5, kpiTop + 7);
  doc.setFontSize(13);
  doc.setTextColor(15, 23, 42);
  doc.text(`${report.summary.periodAverage.toLocaleString()}`, margin + colWidth * 3 + 5, kpiTop + 16);

  // 4. Detailed Data Table
  const tableRows = report.records.map((r) => {
    const goodRate = r.total_eggs > 0 ? ((r.good_eggs / r.total_eggs) * 100).toFixed(1) + "%" : "0.0%";
    return [
      r.production_date,
      r.collection_shift || "—",
      r.flock_identifier,
      r.total_eggs.toLocaleString(),
      r.good_eggs.toLocaleString(),
      r.cracked_eggs.toLocaleString(),
      r.damaged_eggs.toLocaleString(),
      goodRate,
    ];
  });

  const footerRow = [
    [
      "TOTAL",
      "—",
      `${report.records.length} records`,
      report.summary.totalEggs.toLocaleString(),
      report.summary.goodEggs.toLocaleString(),
      report.summary.crackedEggs.toLocaleString(),
      report.summary.damagedEggs.toLocaleString(),
      `${report.summary.goodEggsRate}%`,
    ],
  ];

  autoTable(doc, {
    startY: kpiTop + kpiHeight + 6,
    head: [["Date", "Shift", "Flock", "Total", "Good", "Cracked", "Damaged", "Good %"]],
    body: tableRows.length > 0 ? tableRows : [["No records recorded for this period", "", "", "", "", "", "", ""]],
    foot: tableRows.length > 0 ? footerRow : undefined,
    theme: "striped",
    margin: { left: margin, right: margin, bottom: 20 },
    headStyles: {
      fillColor: [15, 23, 42], // slate-900
      textColor: [255, 255, 255],
      fontSize: 8.5,
      fontStyle: "bold",
      halign: "left",
    },
    footStyles: {
      fillColor: [241, 245, 249], // slate-100
      textColor: [15, 23, 42],
      fontSize: 8.5,
      fontStyle: "bold",
    },
    bodyStyles: {
      fontSize: 8,
      textColor: [51, 65, 85],
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    columnStyles: {
      0: { cellWidth: 26 }, // Date
      1: { cellWidth: 24 }, // Shift
      2: { cellWidth: 34 }, // Flock
      3: { cellWidth: 20, halign: "right" }, // Total
      4: { cellWidth: 20, halign: "right" }, // Good
      5: { cellWidth: 18, halign: "right" }, // Cracked
      6: { cellWidth: 18, halign: "right" }, // Damaged
      7: { cellWidth: 22, halign: "right" }, // Good %
    },
    didDrawPage: (data) => {
      // Footer with page numbering
      const totalPages = doc.getNumberOfPages();
      const currentPage = data.pageNumber;

      doc.setFont("helvetica", "normal");
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184); // slate-400
      doc.text(
        `POULTRY HUB Production Reporting System • Generated ${metadata.generatedAt}`,
        margin,
        pageHeight - 8
      );
      doc.text(
        `Page ${currentPage} of ${totalPages}`,
        pageWidth - margin - 15,
        pageHeight - 8
      );
    },
  });

  const arrayBuffer = doc.output("arraybuffer");
  return Buffer.from(arrayBuffer);
}
